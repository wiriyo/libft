#include "libft.h"

t_list	*ft_lstmap(t_list *lst, void *(*f)(void *), void (*del)(void *))
{
	t_list	*head;
	t_list	*node;
	void	*c;

	head = NULL;
	while (lst)
	{
		c = f(lst->content);
		node = ft_lstnew(c);
		if (!node)
		{
			del(c);
			ft_lstclear(&head, del);
			return (NULL);
		}
		ft_lstadd_back(&head, node);
		lst = lst->next;
	}
	return (head);
}
